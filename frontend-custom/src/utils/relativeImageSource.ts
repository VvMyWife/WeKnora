import { marked, type Token } from 'marked'
import { resolveArtifactRef, type ArtifactRefMeta } from './sandboxArtifactRefs.ts'

export type ImageSourceReference = {
  knowledge_id?: string
  knowledge_base_id?: string
  content?: string
}

function localImagePath(value: string): string | null {
  let path = value.trim()
  if (!path || /^[a-z][a-z0-9+.-]*:|^[/\\#?]/i.test(path)) return null
  try { path = decodeURIComponent(path) } catch { return null }
  path = path.replace(/^\.\//, '')
  if (/[\\\x00-\x1f\x7f:?#]/.test(path) || path.startsWith('/')) return null
  if (path.split('/').some(part => !part || part === '.' || part === '..')) return null
  return /\.(?:png|jpe?g|gif|webp|bmp|tiff?|svg)$/i.test(path) ? path : null
}

const escapeHtml = (value: string) => value.replace(/[&<>"']/g, c =>
  ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]!))
const uuid = /^[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}$/i

/** Resolve only exact image paths in evidence chunks, never by basename/title. */
export function relativeImageSourceHtml(href: string, references: ImageSourceReference[] = [], artifacts: ArtifactRefMeta[] = []): string | null {
  // Real generated attachments always win over a similarly named evidence image.
  if (resolveArtifactRef(href, artifacts)) return null
  const sandbox = /^sandbox:(?:\/\/)?(.+)$/i.exec(href.trim())
  const path = localImagePath(sandbox ? sandbox[1] : href)
  if (!path) return null
  const candidates = new Map<string, ImageSourceReference>()
  for (const ref of references) {
    if (!uuid.test(ref.knowledge_id || '') || !uuid.test(ref.knowledge_base_id || '') || !ref.content) continue
    let match = false
    marked.walkTokens(marked.lexer(ref.content), (token: Token) => {
      if (token.type !== 'image') return
      const source = localImagePath(token.href)
      if (source === path || (sandbox && !path.includes('/') && source?.split('/').pop() === path)) match = true
    })
    if (match) candidates.set(`${ref.knowledge_base_id}:${ref.knowledge_id}`, ref)
  }
  const label = escapeHtml(path)
  if (candidates.size !== 1) {
    return `<span class="chat-relative-image-source">图片 ${label} 未提供可访问附件，无法唯一确认来源，请从参考资料查看原件。</span>`
  }
  const ref = [...candidates.values()][0]
  const url = `/platform/knowledge-bases/${ref.knowledge_base_id}?knowledge_id=${ref.knowledge_id}`
  return `<a class="chat-relative-image-source" href="${url}">预览对应原件（图片 ${label}）</a>`
}

/** Only local, scoped source links generated by this renderer may open the drawer. */
export function knowledgeSourcePreviewID(href: string, origin: string): string | null {
  try {
    const url = new URL(href, origin)
    const match = /^\/platform\/knowledge-bases\/([^/]+)$/.exec(url.pathname)
    const id = url.searchParams.get('knowledge_id') || ''
    return url.origin === origin && match && uuid.test(match[1]) && uuid.test(id) ? id : null
  } catch { return null }
}
